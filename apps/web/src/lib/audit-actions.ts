/**
 * Texto de una acción que llega del servidor (`string`). La tabla de auditoría conserva
 * filas de versiones anteriores (y un agente más nuevo puede registrar acciones que esta
 * web no conoce): una acción fuera del catálogo se **declara** en vez de pintar el
 * identificador crudo.
 */
export function etiquetaDeAccion(
  action: string,
  t: (key: TranslationKey, params?: TranslationParams) => string,
): string {
  return Object.prototype.hasOwnProperty.call(ETIQUETA_DE_ACCION, action)
    ? t(ETIQUETA_DE_ACCION[action as AuditAction])
    : t('audit.action.unknown', { action });
}
